// Build script: generates the interrupt entry stubs and hands the linker script to the linker.
use std::fmt::Write as _;
use std::path::PathBuf;

/// Vectors for which the CPU itself pushes an error code.
fn has_error_code(vector: usize) -> bool {
    matches!(vector, 8 | 10..=14 | 17 | 21 | 29 | 30)
}

/// Generates one tiny assembly entry stub per interrupt vector (0..=255).
/// Each stub normalises the stack (pushes a dummy error code when the CPU
/// didn't) and then pushes its vector number before jumping to the shared
/// `isr_common` code in `src/hal/idt.rs`.
fn generate_isr_stubs() {
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR not set"));
    let mut s = String::from("// Generated by build.rs - do not edit.\n.text\n");
    for v in 0..256usize {
        writeln!(s, ".balign 16\nisr_stub_{v}:").unwrap();
        if !has_error_code(v) {
            s.push_str("    push 0\n");
        }
        writeln!(s, "    push {v}\n    jmp isr_common").unwrap();
    }
    s.push_str(".section .rodata\n.balign 8\n.global isr_stub_table\nisr_stub_table:\n");
    for v in 0..256usize {
        writeln!(s, "    .quad isr_stub_{v}").unwrap();
    }
    s.push_str(".text\n");
    std::fs::write(out.join("isr_stubs.S"), s).expect("failed to write isr_stubs.S");
}

fn main() {
    generate_isr_stubs();
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    println!("cargo:rustc-link-arg-bins=-T{dir}/linker.ld");
    // Never emit a PIE: the kernel is linked at a fixed higher-half address
    // and packed into an LXF image from a static executable.
    println!("cargo:rustc-link-arg-bins=--no-pie");
    println!("cargo:rerun-if-changed=linker.ld");
    println!("cargo:rerun-if-changed=build.rs");
}
